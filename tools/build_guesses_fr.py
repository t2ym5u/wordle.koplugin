#!/usr/bin/env python3
# Builds guesses_fr.lua: the French 5-letter words Wordle accepts as guesses
# but never draws as answers. Run from the monorepo root:
#
#   python3 wordle.koplugin/tools/build_guesses_fr.py
#
# Source: boggle.koplugin/words_fr.lua, both blocks (the CC0 Scrabble-valid
# list, and the Grammalecte lexicon's forms added by
# boggle.koplugin/tools/lexicon_fr.py, filtered for family play there). Kept:
# 5-letter words not already in words_fr.lua, the answer list, which this
# script never touches -- so no answer and no valid guess is ever removed.
import os, re

ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
BOGGLE = os.path.join(os.path.dirname(ROOT), "boggle.koplugin")


def words_of(path):
    text = open(path, encoding="utf-8").read()
    return {w.upper() for b in re.findall(r"\[\[(.*?)\]\]", text, re.S) for w in re.findall(r"[A-Za-z]+", b)}


def wrap(words, width=150):
    lines, line = [], ""
    for w in words:
        if line and len(line) + len(w) + 1 > width:
            lines.append(line)
            line = ""
        line += w + ","
    lines.append(line)
    return "\n".join(lines)


def main():
    answers = words_of(os.path.join(ROOT, "words_fr.lua"))
    guesses = sorted(w for w in words_of(os.path.join(BOGGLE, "words_fr.lua")) if len(w) == 5)
    guesses = [w for w in guesses if w not in answers]
    with open(os.path.join(ROOT, "guesses_fr.lua"), "w", encoding="utf-8") as f:
        f.write(f"""-- French 5-letter words accepted as Wordle guesses but never used as answers
-- {len(guesses)} words (generated by tools/build_guesses_fr.py, do not edit)
--
-- See words_fr.lua for the answer list and board.lua for why the two are
-- separate. Source: boggle.koplugin/words_fr.lua, i.e. the CC0 Scrabble-valid
-- list and forms of the Grammalecte lexicon v7.7 (Olivier R., Dicollecte,
-- https://grammalecte.net, Mozilla Public License 2.0), minus familiar,
-- pejorative, slang and sexual words; see that file for the full credits.
local words = {{}}
local raw = [[
{wrap(guesses)}
]]
for w in raw:gmatch("[A-Z]+") do
    words[#words + 1] = w
end
return words
""")
    print("guesses_fr.lua:", len(guesses), "words")


if __name__ == "__main__":
    main()
