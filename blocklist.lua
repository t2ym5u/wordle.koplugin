local sets = {}

local M = {}

-- word -> true for `lang` ("en" or "fr"; anything else gets English).
function M.set(lang)
    lang = (lang == "fr") and "fr" or "en"
    local s = sets[lang]
    if not s then
        s = {}
        for w in raw[lang]:gmatch("%u+") do s[w] = true end
        sets[lang] = s
    end
    return s
end

-- True when `word` (any case) must never be drawn or shown in `lang`.
function M.isBlocked(word, lang)
    return M.set(lang)[word:upper()] == true
end

-- A copy of the array `list` without its blocked words.
function M.filter(list, lang)
    local s, out = M.set(lang), {}
    for i = 1, #list do
        local w = list[i]
        if not s[w:upper()] then out[#out + 1] = w end
    end
    return out
end

-- Drops the built sets (the game screen closing); rebuilt on next use.
function M.release()
    sets = {}
end

return M
